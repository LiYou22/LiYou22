"""Export the pixel art the banner uses to docs/sprites.js, so the game draws the same sprites.

Run after changing any sprite or palette: python3 scripts/sprites.py
"""

import json
from pathlib import Path

import banner
from pixel import FISH, FONT, THEMES, mono_whale

sprites = {
    "font": FONT,
    "whale": [mono_whale(False), mono_whale(True)],
    "kelp": banner.KELP,
    "jelly": banner.JELLY,
    "rock": banner.ROCK,
    "cloud": banner.CLOUD,
    "moon": banner.MOON,
    "fish": FISH,
    "themes": THEMES,
}
out = Path(__file__).resolve().parent.parent / "docs" / "sprites.js"
out.parent.mkdir(exist_ok=True)
out.write_text("// Generated by scripts/sprites.py; do not edit.\nwindow.SPRITES = " + json.dumps(sprites) + ";\n")
